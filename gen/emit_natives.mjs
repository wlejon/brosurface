// gen/emit_natives.mjs — the natives emitter: from idl/<subsystem>.idl to
// out/natives/<subsystem>/{native_<sub>_decl.h, native_<sub>_register.cpp,
// <sub>.js, module.globals}.
//
// What is generated and what is not (README.md "Natives"):
//   generated     the C prototypes (the compiler checks bro's bodies against
//                 them), the embed::registerNative calls with their
//                 signatures, the JavaScript wrapper mechanics (mounts,
//                 dictionary unpacking, result assembly, class shapes), the
//                 host-globals fragment
//   hand-written  the entry-point bodies (in bro, against the engine and the
//                 sibling libraries), and every [manual] member's JS
//
// Which subsystems: the ones idl/natives.list names, or the IDL files given
// on the command line. A subsystem whose IDL the bronze vocabulary cannot
// carry is refused with the IDL line and the nearest spelling, never emitted
// with a `dynamic` in it.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokenize } from '../schema/lexer.mjs';
import { parse } from '../schema/parser.mjs';
import { validate } from '../schema/validator.mjs';
import { NATIVE_ROOT } from '../schema/native_types.mjs';
import { planNatives, JS_HELPERS } from './natives_plan.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const INDENT = '    ';

/** Reads idl/natives.list: one subsystem (IDL basename) per line, `#` comments. */
export function readNativesList(idlDir) {
  const file = path.join(idlDir, 'natives.list');
  if (!fs.existsSync(file)) return [];
  return fs.readFileSync(file, 'utf8')
    .split('\n')
    .map((l) => l.replace(/#.*$/, '').trim())
    .filter(Boolean);
}

/** Every IDL under idlDir, parsed, with its subsystem name. */
export function loadIdls(idlDir) {
  const entries = [];
  const sourceMap = new Map();
  for (const name of fs.readdirSync(idlDir).filter((f) => f.endsWith('.idl')).sort()) {
    const full = path.join(idlDir, name);
    const rel = path.relative(process.cwd(), full).replace(/\\/g, '/');
    const src = fs.readFileSync(full, 'utf8');
    sourceMap.set(rel, src);
    const fileAst = parse(tokenize(src, rel), rel);
    entries.push({ fileAst, subsystem: path.basename(name, '.idl'), rel });
  }
  return { entries, sourceMap };
}

// ---- rendering: the declaration header --------------------------------------------

function cPrototype(n) {
  const params = n.cParams.length === 0 ? 'void' : n.cParams.map((p) => `${p.c} ${p.name}`).join(', ');
  return `${n.ret.c} ${n.cName}(${params});`;
}

function nativeComment(n) {
  const lines = [];
  if (n.comment) lines.push(`// ${n.comment}`);
  if (n.kind === 'getter' || n.kind === 'setter') lines.push(`//   registered as a namespace property (${n.kind}) at ${n.jsPath}`);
  else if (n.jsPath) lines.push(`//   registered at ${n.jsPath}`);
  const jsonParams = n.cParams.filter((p) => p.json);
  for (const p of jsonParams) lines.push(`//   ${p.name}: JSON of ${p.json}`);
  if (n.ret.json) lines.push(`//   result: JSON of ${n.ret.json}`);
  if (n.ret.buffer) {
    lines.push(n.transfer
      ? `//   result: ${n.ret.bronze} in *out; [transfer]: the body must set out->release (zero-copy)`
      : `//   result: ${n.ret.bronze} in *out; out->release == NULL, the runtime copies`);
  }
  const given = n.cParams.filter((p) => p.name.endsWith('_given'));
  if (given.length) lines.push(`//   ${given.map((p) => p.name).join(', ')}: false when the value was not passed (no declared default)`);
  return lines;
}

export function renderDeclHeader(plan) {
  const sub = plan.subsystem;
  const out = [];
  out.push(`// native_${sub}_decl.h — the C entry points behind idl/${sub}.idl, one prototype per`);
  out.push(`// native. Generated by brosurface (gen/emit_natives.mjs); do not edit. The bodies`);
  out.push(`// are hand-written in bro against the engine, and the compiler checks them here.`);
  out.push(`//`);
  out.push(`// How each type crosses (schema/native_types.mjs, bronze/src/abi/bronze_native_type.h):`);
  out.push(`//   double / int32_t / bool      f64 / i32 / bool`);
  out.push(`//   const char*                  str — UTF-8, valid for the call only; a RESULT must`);
  out.push(`//                                outlive the return (a per-thread scratch), and one`);
  out.push(`//                                marked JSON carries JSON of the IDL type in the comment`);
  out.push(`//   uint64_t                     dynamic — a callback's raw Value bits; keep it in a`);
  out.push(`//                                Persistent, never across an allocating call raw`);
  out.push(`//   (const T*, uint32_t)         a typed array: elements and count, valid for the call`);
  out.push(`//   void*                        a class handle: what the class constructor returned`);
  out.push(`//   bronze_native_buffer* out    a typed-array RESULT: the function returns void and`);
  out.push(`//                                fills *out (data, length in elements); release == NULL`);
  out.push(`//                                and the runtime copies during the call; release set`);
  out.push(`//                                ([transfer]) and the array is a view over data, with`);
  out.push(`//                                release(ctx) run when it is collected`);
  out.push(`//   bool <x>_given, T <x>        an optional value with no declared default, and`);
  out.push(`//                                whether it was passed`);
  out.push(`//`);
  out.push(`// A dictionary or list RESULT crosses as reads: the operation runs and keeps its`);
  out.push(`// result in a per-thread slot, answering nothing (or the list's length), and the`);
  out.push(`// <op>_<member> / <op>_at natives read from that slot until the next call.`);
  if (plan.gate) out.push(`//`, `// Gate: ${plan.gate} (native_${sub}_register.cpp registers nothing when it is off).`);
  if (plan.dependsOn.length) out.push(`//`, `// Names classes of: ${plan.dependsOn.join(', ')} — register those subsystems first.`);
  out.push('#pragma once');
  out.push('');
  out.push('#include <stdbool.h>');
  out.push('#include <stdint.h>');
  out.push('');
  out.push('#include "abi/bronze_native_type.h"  // bronze_native_buffer, owned by bronze');
  out.push('');
  out.push('#ifdef __cplusplus');
  out.push('extern "C" {');
  out.push('#endif');
  for (const n of plan.natives) {
    out.push('');
    if (n.gate && !plan.gate) out.push(`#if ${n.gate}`);
    out.push(...nativeComment(n));
    out.push(cPrototype(n));
    if (n.gate && !plan.gate) out.push(`#endif`);
  }
  out.push('');
  out.push('#ifdef __cplusplus');
  out.push('}  // extern "C"');
  out.push('#endif');
  out.push('');
  return out.join('\n');
}

// ---- rendering: the registration TU -------------------------------------------------

function quoted(list) {
  return `{${list.map((s) => JSON.stringify(s)).join(', ')}}`;
}

export function renderRegisterCpp(plan) {
  const sub = plan.subsystem;
  const fnName = `registerNatives_${sub}`;
  const out = [];
  out.push(`// native_${sub}_register.cpp — registers every native of native_${sub}_decl.h with`);
  out.push(`// bronze (embed::registerNative) under ${NATIVE_ROOT}.${sub}. Generated by brosurface`);
  out.push(`// (gen/emit_natives.mjs); do not edit. Call ${fnName} from registerBroNatives`);
  out.push(`// (src/bronze_host/host_natives.h) on the thread that runs the program${plan.dependsOn.length ? `, after ${plan.dependsOn.map((d) => `registerNatives_${d}`).join(', ')}` : ''}.`);
  out.push(`//`);
  out.push(`// Class members are Function-kind natives taking the handle first (the wrapper's`);
  out.push(`// receiver is dynamic, so a Method-kind registration would be unreachable from it);`);
  out.push(`// each class has one Constructor-kind registration, which mints the class, and its`);
  out.push(`// prototype is published as ${NATIVE_ROOT}.${sub}.<Class>Proto for ${sub}.js to chain.`);
  out.push('');
  out.push(`#include "native_${sub}_decl.h"`);
  out.push('');
  if (plan.gate) {
    out.push(`#if ${plan.gate}`);
    out.push('');
  }
  out.push('#include "embed/embed.h"');
  out.push('');
  out.push('#include <initializer_list>');
  out.push('#include <string>');
  out.push('');
  out.push('namespace bro::bronze_host {');
  out.push('');
  out.push('namespace {');
  out.push('');
  out.push('namespace ev = bronze::embed;');
  out.push('');
  // The registration lines first: only the helpers they use are emitted.
  const regs = [];
  const used = new Set();
  for (const n of plan.natives) {
    if (n.kind === 'dtor') continue;
    let callStr;
    if (n.kind === 'ctor') {
      used.add('ctor');
      callStr = `ctor(${JSON.stringify(n.jsPath)}, p(&${n.cName}), ${n.dtor ? `&${n.dtor}` : 'nullptr'}, bronze::runtime::Finalize::${n.finalize}, ${quoted(n.bronzeParams)}, error)`;
    } else if (n.kind === 'getter') {
      used.add('getter');
      callStr = `getter(${JSON.stringify(n.jsPath)}, p(&${n.cName}), ${JSON.stringify(n.ret.bronze)}, error)`;
    } else if (n.kind === 'setter') {
      used.add('setter');
      callStr = `setter(${JSON.stringify(n.jsPath)}, p(&${n.cName}), ${JSON.stringify(n.bronzeParams[0])}, error)`;
    } else {
      used.add('fn');
      callStr = `fn(${JSON.stringify(n.jsPath)}, p(&${n.cName}), ${JSON.stringify(n.ret.bronze)}, ${quoted(n.bronzeParams)}, error)`;
    }
    regs.push({ callStr, gate: (plan.gate ? null : (n.gate || null)) });
  }
  if (regs.length) {
    out.push('ev::NativeSignature sig(const char* ret, std::initializer_list<const char*> params, ev::NativeKind kind) {');
    out.push('    ev::NativeSignature s;');
    out.push('    s.returnType = ret;');
    out.push('    for (const char* p : params) s.paramTypes.emplace_back(p);');
    out.push('    s.kind = kind;');
    out.push('    return s;');
    out.push('}');
    out.push('');
  }
  if (used.has('fn')) {
    out.push('bool fn(const char* path, void* f, const char* ret, std::initializer_list<const char*> params, std::string* error) {');
    out.push('    return ev::registerNative(path, f, sig(ret, params, ev::NativeKind::Function), error);');
    out.push('}');
    out.push('');
  }
  if (used.has('getter')) {
    out.push('bool getter(const char* path, void* f, const char* ret, std::string* error) {');
    out.push('    return ev::registerNative(path, f, sig(ret, {}, ev::NativeKind::Getter), error);');
    out.push('}');
    out.push('');
  }
  if (used.has('setter')) {
    out.push('bool setter(const char* path, void* f, const char* type, std::string* error) {');
    out.push('    return ev::registerNative(path, f, sig("void", {type}, ev::NativeKind::Setter), error);');
    out.push('}');
    out.push('');
  }
  if (used.has('ctor')) {
    out.push('bool ctor(const char* path, void* f, ev::HandleDestructor dtor, bronze::runtime::Finalize finalize,');
    out.push('          std::initializer_list<const char*> params, std::string* error) {');
    out.push('    ev::NativeSignature s = sig(path, params, ev::NativeKind::Constructor);');
    out.push('    s.className = path;');
    out.push('    s.destructor = dtor;');
    out.push('    s.finalize = finalize;');
    out.push('    return ev::registerNative(path, f, s, error);');
    out.push('}');
    out.push('');
    out.push('// The prototype every instance of a class is born on, published where the');
    out.push('// wrapper reads it. Skipped when the roots are not there (bro-native-manifest');
    out.push('// registers without them; the manifest does not need the prototype).');
    out.push('void publishPrototype(const char* ns, const char* className, const char* protoName) {');
    out.push(`    ev::GlobalValue root = ev::globalValue("${NATIVE_ROOT}");`);
    out.push('    if (!root.found || !ev::isObject(root.value)) return;');
    out.push('    ev::GlobalValue proto = ev::nativeClassPrototype(className);');
    out.push('    if (!proto.found) return;');
    out.push('    // Each value rooted before the next allocating call (bronze embed GC contract).');
    out.push('    ev::Persistent rootSlot(root.value);');
    out.push('    ev::Persistent protoSlot(proto.value);');
    out.push('    ev::Persistent nsSlot(ev::getProperty(rootSlot.get(), ns));');
    out.push('    if (!ev::isObject(nsSlot.get())) return;');
    out.push('    ev::setProperty(nsSlot.get(), protoName, protoSlot.get());');
    out.push('}');
    out.push('');
  }
  if (regs.length) {
    out.push('template <typename F>');
    out.push('void* p(F* f) { return reinterpret_cast<void*>(f); }');
    out.push('');
  }
  out.push('}  // namespace');
  out.push('');
  out.push(`bool ${fnName}(std::string* error) {`);
  if (regs.length === 0) {
    out.push('    (void)error;');
    out.push('    return true;');
  } else {
    const hasGated = regs.some((r) => r.gate);
    if (!hasGated) {
      out.push('    const bool ok =');
      regs.forEach((r, i) => out.push(`        ${r.callStr}${i === regs.length - 1 ? ';' : ' &&'}`));
    } else {
      const ungated = regs.filter((r) => !r.gate);
      const gated = regs.filter((r) => r.gate);
      out.push('    bool ok =');
      ungated.forEach((r, i) => out.push(`        ${r.callStr}${i === ungated.length - 1 ? ';' : ' &&'}`));
      const gateMap = new Map();
      for (const r of gated) {
        if (!gateMap.has(r.gate)) gateMap.set(r.gate, []);
        gateMap.get(r.gate).push(r.callStr);
      }
      for (const [gate, calls] of gateMap) {
        out.push(`#if ${gate}`);
        out.push('    ok = ok &&');
        calls.forEach((c, i) => out.push(`        ${c}${i === calls.length - 1 ? ';' : ' &&'}`));
        out.push('#endif');
      }
    }
    out.push('    if (!ok) return false;');
    for (const n of plan.natives) {
      if (n.kind !== 'ctor') continue;
      out.push(`    publishPrototype(${JSON.stringify(sub)}, ${JSON.stringify(n.jsPath)}, ${JSON.stringify(`${n.publicName}Proto`)});`);
    }
    out.push('    return true;');
  }
  out.push('}');
  out.push('');
  out.push('}  // namespace bro::bronze_host');
  if (plan.gate) {
    out.push('');
    out.push(`#else  // !(${plan.gate})`);
    out.push('');
    out.push('#include <string>');
    out.push('');
    out.push('namespace bro::bronze_host {');
    out.push('');
    out.push(`// Compiled out: nothing is registered and ${sub}.js is not to be installed.`);
    out.push(`bool ${fnName}(std::string*) { return true; }`);
    out.push('');
    out.push('}  // namespace bro::bronze_host');
    out.push('');
    out.push(`#endif  // ${plan.gate}`);
  }
  out.push('');
  return out.join('\n');
}

// ---- rendering: the wrapper ------------------------------------------------------------

function indentLines(lines, depth) {
  const pad = INDENT.repeat(depth);
  return lines.map((l) => (l === '' ? '' : pad + l));
}

function functionText(name, params, lines) {
  return [`function ${name}(${params.join(', ')}) {`, ...indentLines(lines, 1), '}'];
}

function memberLines(owner, m, publicOwner) {
  const out = [];
  switch (m.kind) {
    case 'constant':
      out.push(...m.lines);
      break;
    case 'accessor': {
      const get = ['function () {', ...indentLines(m.getLines, 1), '}'];
      const set = m.setLines ? ['function (v) {', ...indentLines(m.setLines, 1), '}'] : ['undefined'];
      out.push(`accessor(${owner}, ${JSON.stringify(m.name)},`);
      out.push(...indentLines([...get.slice(0, -1), `${get[get.length - 1]},`], 1));
      out.push(...indentLines([...set.slice(0, -1), `${set[set.length - 1]});`], 1));
      break;
    }
    case 'getterOp': {
      const get = ['function () {', ...indentLines(m.lines, 1), '}'];
      out.push(`accessor(${owner}, ${JSON.stringify(m.name)},`);
      out.push(...indentLines([...get.slice(0, -1), `${get[get.length - 1]},`], 1));
      out.push(...indentLines(['undefined);'], 1));
      break;
    }
    case 'operation': {
      const f = functionText(m.name, m.params, m.lines);
      out.push(`fn(${owner}, ${JSON.stringify(m.name)}, ${f[0]}`);
      out.push(...f.slice(1, -1));
      out.push(`${f[f.length - 1]});`);
      break;
    }
    case 'manual':
      out.push(`// [manual] ${publicOwner}.${m.name}: ${m.note} — no native is generated; hand-written JS`);
      out.push(`// installs it on ${owner} after this module has run.`);
      break;
    case 'error':
      out.push(`// (refused) ${m.name}`);
      break;
    default:
      break;
  }
  return out;
}

export function renderWrapper(plan) {
  const sub = plan.subsystem;
  const w = plan.wrapper;
  const out = [];
  const publicNames = [
    ...w.namespaces.map((ns) => ns.publicPath),
    ...w.classes.map((c) => c.publicPath),
  ];
  out.push(`// ${sub}.js — the public shape of ${publicNames.join(', ')}, assembled over the`);
  out.push(`// natives under ${NATIVE_ROOT}.${sub} (native_${sub}_decl.h states each C entry point,`);
  out.push(`// native_${sub}_register.cpp registers them). Generated by brosurface`);
  out.push(`// (gen/emit_natives.mjs) from idl/${sub}.idl; do not edit.`);
  out.push(`//`);
  out.push(`// Every native is spelled by its full dotted path at the point of use: that is the`);
  out.push(`// spelling the compiler lowers to a direct call. The roots this module reads as bare`);
  out.push(`// identifiers are listed in module.globals beside it.`);
  if (plan.manual.length) {
    out.push(`//`);
    out.push(`// [manual] members (no native, installed by hand-written JS after this module):`);
    for (const m of plan.manual) out.push(`//   ${m.publicPath}.${m.member}`);
  }
  out.push('(function () {');
  out.push(`${INDENT}'use strict';`);
  out.push('');
  out.push(`${INDENT}const accessor = (obj, name, get, set) =>`);
  out.push(`${INDENT}${INDENT}Object.defineProperty(obj, name, { get, set, enumerable: true, configurable: true });`);
  out.push(`${INDENT}const fn = (obj, name, value) =>`);
  out.push(`${INDENT}${INDENT}Object.defineProperty(obj, name, { value, writable: true, enumerable: true, configurable: true });`);
  for (const h of [...w.helpers].sort()) {
    out.push(`${INDENT}${JS_HELPERS[h]}`);
  }

  for (const ns of w.namespaces) {
    out.push('');
    out.push(`${INDENT}// ---- ${ns.publicPath} ${'-'.repeat(Math.max(4, 68 - ns.publicPath.length))}`);
    out.push(`${INDENT}const ${ns.local} = ${ns.mountExpr};`);
    for (const m of ns.members) out.push(...indentLines(memberLines(ns.local, m, ns.publicPath), 1));
  }

  for (const c of w.classes) {
    out.push('');
    out.push(`${INDENT}// ---- ${c.publicPath} ${'-'.repeat(Math.max(4, 68 - c.publicPath.length))}`);
    const ctorLines = [];
    if (c.ctor.kind === 'generated') {
      ctorLines.push(...c.ctor.prelude);
      ctorLines.push(`return new ${c.path}(${c.ctor.jsArgs.join(', ')});`);
      out.push(...indentLines(functionText(c.name, c.ctor.params, ctorLines), 1));
    } else if (c.ctor.kind === 'manual') {
      out.push(`${INDENT}// [manual] constructor of ${c.publicPath}: hand-written JS replaces ${c.publicPath} with a`);
      out.push(`${INDENT}// function of its own, reusing ${c.name}.prototype (\`new ${c.path}()\` mints an instance).`);
      out.push(...indentLines(functionText(c.name, [], [`throw new TypeError(${JSON.stringify(`${c.publicPath}: the constructor is [manual] and not installed`)});`]), 1));
    } else {
      out.push(...indentLines(functionText(c.name, [], [`throw new TypeError(${JSON.stringify(`${c.publicPath} is not constructible: instances come from the natives that return one`)});`]), 1));
    }
    // The handle prototype the registry minted chains to the wrapper's, so
    // `instanceof` answers and a dynamic call reaches the methods below.
    out.push(`${INDENT}{`);
    out.push(`${INDENT}${INDENT}const proto = ${NATIVE_ROOT}.${sub}.${c.name}Proto;`);
    out.push(`${INDENT}${INDENT}if (proto === undefined) throw new Error(${JSON.stringify(`${c.publicPath}: native class prototype not published (registerNatives_${sub} did not run)`)});`);
    out.push(`${INDENT}${INDENT}Object.setPrototypeOf(proto, ${c.name}.prototype);`);
    out.push(`${INDENT}}`);
    out.push(`${INDENT}fn(${c.mountExpr}, ${JSON.stringify(c.mountName)}, ${c.name});`);
    for (const k of c.constants) {
      out.push(`${INDENT}Object.defineProperty(${c.name}, ${JSON.stringify(k.name)}, { value: ${k.value}, enumerable: true });`);
      out.push(`${INDENT}Object.defineProperty(${c.name}.prototype, ${JSON.stringify(k.name)}, { value: ${k.value}, enumerable: true });`);
    }
    for (const m of c.members) out.push(...indentLines(memberLines(`${c.name}.prototype`, m, `${c.publicPath}.prototype`), 1));
    for (const m of c.statics) out.push(...indentLines(memberLines(c.name, m, c.publicPath), 1));
  }
  out.push('})();');
  out.push('');
  return out.join('\n');
}

export function renderGlobals(plan) {
  const out = [];
  out.push(`# ${plan.subsystem}.js reads these bare identifiers (bronze --host-globals). Generated by`);
  out.push(`# brosurface (gen/emit_natives.mjs); concatenate into bro's module.globals.`);
  for (const r of plan.wrapper.reads) out.push(r);
  return out.join('\n') + '\n';
}

