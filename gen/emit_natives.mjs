/**
 * Plans every requested subsystem. Throws with every refusal listed when one
 * cannot be carried; otherwise answers the plans.
 */
export function planSubsystems(idlDir, subsystems) {
  const { entries, sourceMap } = loadIdls(idlDir);
  const valErrors = validate(entries.map((e) => e.fileAst), sourceMap);
  if (valErrors.length > 0) {
    throw new Error(`IDL validation failed:\n${valErrors.map((e) => '  ' + e.toString()).join('\n')}`);
  }
  const known = new Set(entries.map((e) => e.subsystem));
  for (const s of subsystems) {
    if (!known.has(s)) throw new Error(`natives subsystem '${s}' has no idl/${s}.idl`);
  }
  const plans = [];
  const errors = [];
  for (const s of subsystems) {
    const plan = planNatives(entries, s, subsystems);
    for (const e of plan.errors) {
      const src = sourceMap.get(e.file);
      if (src && !e.sourceSnippet) {
        const line = src.split('\n')[e.line - 1];
        if (line !== undefined) e.sourceSnippet = line.length > 160 ? line.slice(0, 160) + '…' : line;
      }
      errors.push(e);
    }
    plans.push(plan);
  }
  if (errors.length > 0) {
    throw new Error(`natives emitter refused ${errors.length} declaration(s):\n${errors.map((e) => '  ' + e.toString()).join('\n')}`);
  }
  return plans;
}

export function writePlan(plan, outDir) {
  const dir = path.join(outDir, plan.subsystem);
  fs.mkdirSync(dir, { recursive: true });
  const files = {
    [`native_${plan.subsystem}_decl.h`]: renderDeclHeader(plan),
    [`native_${plan.subsystem}_register.cpp`]: renderRegisterCpp(plan),
    [`${plan.subsystem}.js`]: renderWrapper(plan),
    'module.globals': renderGlobals(plan),
  };
  const written = [];
  for (const [name, content] of Object.entries(files)) {
    const full = path.join(dir, name);
    fs.writeFileSync(full, content, 'utf8');
    written.push(full);
  }
  return written;
}

/**
 * The emitter entry point. `subsystems` empty = idl/natives.list.
 * @returns {{ plans: Object[], files: string[] }}
 */
export function runEmitNatives(idlDir = 'idl/', outDir = 'out/natives/', subsystems = []) {
  const list = subsystems.length ? subsystems : readNativesList(idlDir);
  console.log(`[brosurface Natives Emitter] ${list.length} subsystem(s) from ${idlDir}: ${list.join(', ')}`);
  const plans = planSubsystems(idlDir, list);
  fs.mkdirSync(outDir, { recursive: true });
  const files = [];
  for (const plan of plans) {
    const written = writePlan(plan, outDir);
    files.push(...written);
    console.log(`  - ${plan.subsystem}: ${plan.natives.length} natives, ${plan.manual.length} [manual]${plan.gate ? `, gate ${plan.gate}` : ''}`);
  }
  console.log(`✅ Natives emitter: ${files.length} file(s) under ${outDir}`);
  return { plans, files };
}

const isDirect = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename);
if (isDirect) {
  const args = process.argv.slice(2);
  const idlDir = args[0] || path.join(ROOT, 'idl');
  const outDir = args[1] || path.join(ROOT, 'out', 'natives');
  const subs = args.slice(2).map((a) => path.basename(a, '.idl'));
  try {
    runEmitNatives(idlDir, outDir, subs);
  } catch (err) {
    console.error(`❌ ${err.message}`);
    process.exit(1);
  }
}
